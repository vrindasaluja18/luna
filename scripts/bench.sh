#!/usr/bin/env bash
# Regenerate the benchmark report.
#
#   scripts/bench.sh [PATH_TO_SLAMCORE] [SEEDS...]
#
# Every number in docs/benchmark_report.md comes from a run of the binary
# passed in (or build/slamcore by default), so the report can always be traced
# back to a command. Peak RSS is read from /usr/bin/time where available and
# skipped, not guessed, where it is not.

set -u

BIN="${1:-build/slamcore}"
shift 2>/dev/null || true
SEEDS=("$@")
if [ ${#SEEDS[@]} -eq 0 ]; then
  SEEDS=(1 2 3 4 5 6 7 8)
fi

if [ ! -x "$BIN" ]; then
  echo "error: $BIN not found or not executable" >&2
  exit 1
fi

WORLDS=(rooms corridor_loop saddle_hall maze cluttered textureless)
DURATION=30
OUT=docs/benchmark_report.md
mkdir -p docs

# Peak RSS in KB, or "n/a" when it cannot be measured.
#
# GNU time gives the kernel's own high-water mark but is not installed
# everywhere, so fall back to polling VmHWM from /proc. Polling can miss a
# spike between samples, so it is a lower bound; that is why the method is
# recorded alongside the number rather than presented as exact.
peak_rss_kb() {
  if command -v /usr/bin/time >/dev/null 2>&1; then
    local rss
    rss=$(/usr/bin/time -f '%M' "$@" 2>&1 >/dev/null | tail -1)
    case "$rss" in
      ''|*[!0-9]*) echo "n/a gnu-time" ;;
      *) echo "$rss gnu-time" ;;
    esac
    return
  fi
  if [ ! -r /proc/self/status ]; then
    echo "n/a none"
    return
  fi
  "$@" >/dev/null 2>&1 &
  local pid=$! peak=0 hwm
  while kill -0 "$pid" 2>/dev/null; do
    if [ -r "/proc/$pid/status" ]; then
      hwm=$(awk '/^VmHWM:/{print $2}' "/proc/$pid/status" 2>/dev/null)
      case "$hwm" in
        ''|*[!0-9]*) ;;
        *) [ "$hwm" -gt "$peak" ] && peak=$hwm ;;
      esac
    fi
    sleep 0.05
  done
  wait "$pid" 2>/dev/null
  if [ "$peak" -gt 0 ]; then echo "$peak proc-poll"; else echo "n/a none"; fi
}

field() { grep -oE "$1" | head -1 | grep -oE '[0-9.]+'; }

{
  echo "# SLAMCore-8G benchmark report"
  echo
  echo "Generated by \`make bench\` (\`scripts/bench.sh\`). Every figure below is"
  echo "reproduced from a run of \`$BIN\`; none is hand-written."
  echo
  echo "- binary: \`$BIN\`"
  echo "- seeds: ${SEEDS[*]}"
  echo "- duration per run: ${DURATION} s of simulated time"
  echo
  echo "## Simulator reference runs"
  echo
  echo "A collision here is a defect in the scripted route or the tracker, not in"
  echo "the SLAM frontend: the route is planned with the same clearance field the"
  echo "vehicle is checked against."
  echo
  echo "| world | runs | collision-free | collisions | path (m) | real-time factor |"
  echo "|---|---|---|---|---|---|"
} > "$OUT"

for w in "${WORLDS[@]}"; do
  runs=0; clean=0; collisions=0; path_sum=0; rtf_sum=0
  for s in "${SEEDS[@]}"; do
    out=$("$BIN" sim --type "$w" --seed "$s" --duration "$DURATION" 2>&1)
    c=$(printf '%s\n' "$out" | field 'collisions: [0-9]+')
    p=$(printf '%s\n' "$out" | field 'path *: [0-9.]+ m')
    r=$(printf '%s\n' "$out" | grep -oE '\([0-9.]+x real time\)' | grep -oE '[0-9.]+')
    runs=$((runs + 1))
    collisions=$((collisions + ${c:-0}))
    [ "${c:-1}" = "0" ] && clean=$((clean + 1))
    path_sum=$(awk -v a="$path_sum" -v b="${p:-0}" 'BEGIN{printf "%.1f", a+b}')
    rtf_sum=$(awk -v a="$rtf_sum" -v b="${r:-0}" 'BEGIN{printf "%.2f", a+b}')
  done
  avg_path=$(awk -v s="$path_sum" -v n="$runs" 'BEGIN{printf "%.1f", s/n}')
  avg_rtf=$(awk -v s="$rtf_sum" -v n="$runs" 'BEGIN{printf "%.1f", s/n}')
  printf '| %s | %d | %d | %d | %s | %sx |\n' \
    "$w" "$runs" "$clean" "$collisions" "$avg_path" "$avg_rtf" >> "$OUT"
done

{
  echo
  echo "## Frontend metrics"
  echo
  echo "| world | features/frame | tracked % | track err (px) | stereo depths/frame | ms/frame |"
  echo "|---|---|---|---|---|---|"
} >> "$OUT"

for w in "${WORLDS[@]}"; do
  out=$("$BIN" fe --type "$w" --seed "${SEEDS[0]}" --duration 20 2>&1)
  feats=$(printf '%s\n' "$out" | field 'features *: [0-9.]+')
  pct=$(printf '%s\n' "$out" | grep -oE '\([0-9.]+% of detected\)' | grep -oE '[0-9.]+')
  terr=$(printf '%s\n' "$out" | grep -oE 'mean [0-9.]+ px' | grep -oE '[0-9.]+')
  sd=$(printf '%s\n' "$out" | field 'stereo *: [0-9.]+')
  ms=$(printf '%s\n' "$out" | grep -oE 'total [0-9.]+ ms/frame' | grep -oE '[0-9.]+')
  printf '| %s | %s | %s | %s | %s | %s |\n' \
    "$w" "${feats:-n/a}" "${pct:-n/a}" "${terr:-n/a}" "${sd:-n/a}" "${ms:-n/a}" >> "$OUT"
done

{
  echo
  echo "## End-to-end navigation (SLAM -> map -> topology -> plan -> drive)"
  echo
  echo "The whole stack in one process, scored against the *real* world rather"
  echo "than the map it built. \`blocked\` / \`no_corridor_route\` is the honest"
  echo "outcome when the reconstructed map does not support a route; see the"
  echo "navigation section of the README."
  echo
  echo "| world | plan status | plan (m) | driven (m) | tracking RMS (m) | collisions |"
  echo "|---|---|---|---|---|---|"
} >> "$OUT"

for w in "${WORLDS[@]}"; do
  out=$("$BIN" navigate --type "$w" --seed "${SEEDS[0]}" --duration "$DURATION" 2>&1)
  st=$(printf '%s\n' "$out" | grep -oE 'status *: [a-z_]+' | head -1 | awk '{print $3}')
  pl=$(printf '%s\n' "$out" | field 'length *: [0-9.]+')
  dv=$(printf '%s\n' "$out" | grep -oE 'driven [0-9.]+ m' | head -1 | grep -oE '[0-9.]+')
  rms=$(printf '%s\n' "$out" | grep -oE 'rms [0-9.]+ m' | head -1 | grep -oE '[0-9.]+')
  col=$(printf '%s\n' "$out" | field 'COLLISIONS *: [0-9]+')
  printf '| %s | %s | %s | %s | %s | %s |\n' \
    "$w" "${st:-n/a}" "${pl:-0.0}" "${dv:-0.0}" "${rms:-0.0}" "${col:-0}" >> "$OUT"
done

rss_out=$(peak_rss_kb "$BIN" sim --type rooms --seed "${SEEDS[0]}" --duration "$DURATION")
rss_kb=$(printf '%s' "$rss_out" | awk '{print $1}')
rss_method=$(printf '%s' "$rss_out" | awk '{print $2}')
{
  echo
  echo "## Resource budget"
  echo
  echo "| metric | value | target |"
  echo "|---|---|---|"
  if [ "$rss_kb" = "n/a" ]; then
    echo "| peak RSS | not measurable in this environment | < 5 GB |"
  else
    printf '| peak RSS | %s MB (%s) | < 5 GB |\n' \
      "$(awk -v k="$rss_kb" 'BEGIN{printf "%.0f", k/1024}')" "$rss_method"
  fi
  echo "| simulated duration | ${DURATION} s | - |"
  echo
  echo "Peak RSS is for a single reference run and includes process startup. A"
  echo "\`gnu-time\` reading is the kernel high-water mark; a \`proc-poll\` reading"
  echo "samples VmHWM and can miss a spike between samples, so treat it as a"
  echo "lower bound. The 8 GB budget is a hard constraint on the whole stack; the"
  echo "simulator is the heaviest component because it holds the world grid and"
  echo "landmark field."
} >> "$OUT"

echo "wrote $OUT"
